package com.serratocreations.phovo.buildlogic

import org.gradle.api.DefaultTask
import org.gradle.api.Project
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import org.gradle.kotlin.dsl.configure
import org.gradle.kotlin.dsl.register
import org.jetbrains.kotlin.gradle.dsl.KotlinMultiplatformExtension

/**
 * Generates a `PhovoBuildInfo` object in [packageName] into this module's commonMain, so app code on
 * every platform can read the version from `version.properties` and the build flavor.
 */
fun Project.generatePhovoBuildInfo(packageName: String) {
    val version = phovoVersion()
    val flavor = getBuildFlavor()
    val task = tasks.register<GeneratePhovoBuildInfoTask>("generatePhovoBuildInfo") {
        this.packageName.set(packageName)
        versionName.set(version.name)
        versionCode.set(version.versionCode)
        prerelease.set(version.isPrerelease)
        flavorName.set(flavor.flavorName)
        outputDir.set(layout.buildDirectory.dir("generated/phovoBuildInfo/commonMain/kotlin"))
    }
    extensions.configure<KotlinMultiplatformExtension> {
        sourceSets.getByName("commonMain").kotlin.srcDir(task.flatMap { it.outputDir })
    }
}

@CacheableTask
abstract class GeneratePhovoBuildInfoTask : DefaultTask() {
    @get:Input abstract val packageName: Property<String>
    @get:Input abstract val versionName: Property<String>
    @get:Input abstract val versionCode: Property<Int>
    @get:Input abstract val prerelease: Property<Boolean>
    @get:Input abstract val flavorName: Property<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val pkg = packageName.get()
        val dir = outputDir.get().asFile.resolve(pkg.replace('.', '/'))
        dir.deleteRecursively()
        dir.mkdirs()
        dir.resolve("PhovoBuildInfo.kt").writeText(
            """
            |package $pkg
            |
            |/** Generated by the generatePhovoBuildInfo task from version.properties. Don't edit. */
            |object PhovoBuildInfo {
            |    /** The SemVer version, e.g. 1.0.0-alpha.1. */
            |    const val VERSION_NAME: String = "${versionName.get()}"
            |    /** Android's versionCode, calculated from [VERSION_NAME]. */
            |    const val VERSION_CODE: Int = ${versionCode.get()}
            |    const val IS_PRERELEASE: Boolean = ${prerelease.get()}
            |    /** The build flavor: dev or prod. */
            |    const val FLAVOR: String = "${flavorName.get()}"
            |}
            |""".trimMargin()
        )
    }
}
